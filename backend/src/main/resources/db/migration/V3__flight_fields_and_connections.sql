-- V3 (Disruption Recovery, phase C1): local time zones, scheduled times, real flight fields and connections.
--
--  1. Every block gets the time zone of its start and of its end (for a flight: the departure and the arrival
--     airport), so each time can be shown in the local time of the place it belongs to (landing in Doha = Doha time).
--     A timestamp column stores the exact moment only, not a zone, so the zone is a column of its own.
--  2. Every block gets its scheduled times, which NEVER change. start_time / end_time keep the latest plan
--     (for a flight: the latest estimate after a delay).
--  3. Flight blocks get real flight fields: flight number, airports, terminals and where the flight is in its day.
--  4. A connections table: one row per change of planes (a link between two flights), with its latest check.
--  5. MISSED events become LIKELY_MISSED: they were always predictions made from the times, never confirmed facts.
--
-- Same rules as V1 (read its header): never edit this file once it has run on a shared database, and keep the SQL
-- plain so it runs unchanged on PostgreSQL 17 and on H2 in PostgreSQL mode (the test database). One change per
-- statement, because H2 and PostgreSQL write "several changes in one ALTER TABLE" differently.

-- 1. Time zones. Rows saved before V3 were all in India, hence the one-off default (dropped again right after,
--    so new code must always say which zone it means).
ALTER TABLE blocks ADD COLUMN start_zone VARCHAR(64) DEFAULT 'Asia/Kolkata' NOT NULL;
ALTER TABLE blocks ADD COLUMN end_zone VARCHAR(64) DEFAULT 'Asia/Kolkata' NOT NULL;
ALTER TABLE blocks ALTER COLUMN start_zone DROP DEFAULT;
ALTER TABLE blocks ALTER COLUMN end_zone DROP DEFAULT;

-- 2. Scheduled times. For rows saved before V3 the best we have is their current times (a reset reloads the demo).
ALTER TABLE blocks ADD COLUMN scheduled_start TIMESTAMP WITH TIME ZONE;
ALTER TABLE blocks ADD COLUMN scheduled_end TIMESTAMP WITH TIME ZONE;
UPDATE blocks SET scheduled_start = start_time, scheduled_end = end_time;
ALTER TABLE blocks ALTER COLUMN scheduled_start SET NOT NULL;
ALTER TABLE blocks ALTER COLUMN scheduled_end SET NOT NULL;

-- 3. Flight fields: NULL on every block that is not a flight.
ALTER TABLE blocks ADD COLUMN flight_no VARCHAR(16);    -- e.g. 'IJ 1907'
ALTER TABLE blocks ADD COLUMN dep_airport VARCHAR(3);   -- e.g. 'DEL'
ALTER TABLE blocks ADD COLUMN arr_airport VARCHAR(3);   -- e.g. 'DOH'
ALTER TABLE blocks ADD COLUMN dep_terminal VARCHAR(8);  -- e.g. 'T3'; NULL = not known
ALTER TABLE blocks ADD COLUMN arr_terminal VARCHAR(8);
ALTER TABLE blocks ADD COLUMN flight_phase VARCHAR(16); -- SCHEDULED, BOARDING, IN_AIR, LANDED

-- 4. Connections. Most columns are the latest result of the connection checker (recovery-core), saved so the API
--    and the app's offline copy show exactly what was decided, and when (updated_at, data_as_of).
CREATE TABLE connections (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id                  BIGINT                   NOT NULL REFERENCES trips (id) ON DELETE CASCADE,
    inbound_block_id         BIGINT                   NOT NULL REFERENCES blocks (id) ON DELETE CASCADE, -- flight 1
    outbound_block_id        BIGINT                   NOT NULL REFERENCES blocks (id) ON DELETE CASCADE, -- flight 2
    airport                  VARCHAR(3)               NOT NULL, -- where the traveller changes planes, e.g. 'DOH'
    connection_type          VARCHAR(16),                       -- DOM_DOM, DOM_INTL, INTL_DOM, INTL_INTL; NULL = not known
    terminal_change          BOOLEAN,                           -- NULL = a terminal is not known
    mct_minutes              INT,                               -- minimum connection time; NULL = UNKNOWN
    mct_kind                 VARCHAR(16),                       -- OFFICIAL, DEMO_VALUE, ESTIMATE
    mct_source               VARCHAR(300),
    mct_source_url           VARCHAR(300),
    mct_last_checked         VARCHAR(10),                       -- yyyy-MM-dd
    transfer_minutes         INT                      NOT NULL, -- taxiing + getting off + transfer security (estimate)
    transfer_source          VARCHAR(300)             NOT NULL,
    gate_close_minutes       INT                      NOT NULL, -- the gate closes this long before departure
    gate_close_kind          VARCHAR(16)              NOT NULL,
    gate_close_source        VARCHAR(300)             NOT NULL,
    gate_close_source_url    VARCHAR(300),
    gate_close_last_checked  VARCHAR(10),                       -- yyyy-MM-dd
    ticket_type              VARCHAR(16)              NOT NULL, -- SINGLE_BOOKING, SEPARATE_TICKETS, UNKNOWN
    status                   VARCHAR(24)              NOT NULL, -- OK, AT_RISK, LIKELY_MISSED, CONFIRMED_MISSED, ...
    available_minutes        INT                      NOT NULL, -- landing to next departure; negative = leaves first
    projected_slack_minutes  INT,                               -- available - MCT; NULL when the MCT is unknown
    based_on_demo_value      BOOLEAN                  NOT NULL, -- the status rests on a DEMO VALUE MCT
    reason                   VARCHAR(1000)            NOT NULL, -- plain English, local airport times
    miss_confirmed_at        TIMESTAMP WITH TIME ZONE,          -- set once, when the miss was first confirmed
    updated_at               TIMESTAMP WITH TIME ZONE NOT NULL, -- when this row was last checked
    data_as_of               TIMESTAMP WITH TIME ZONE NOT NULL, -- when the flight data behind it arrived
    CONSTRAINT uq_connections_flights UNIQUE (inbound_block_id, outbound_block_id)
);

CREATE INDEX idx_connections_trip_id ON connections (trip_id);

-- 5. Predictions are called what they are.
UPDATE disruption_events SET kind = 'LIKELY_MISSED' WHERE kind = 'MISSED';
