-- V2: one row per disruption the backend has applied to a trip: a flight delay, a cancellation, ...
-- Written by watcher.DisruptionService every time it runs the ripple engine, so we always know what happened and
-- when. Phase 5 (Plan B) builds its fix options for the latest event of a trip.
--
-- Same rules as V1 (read its header): never edit this file once it has run on a shared database, and keep the SQL
-- plain so it runs unchanged on PostgreSQL 17 and on H2 in PostgreSQL mode (the test database).
--
-- Deleting a trip or a block also deletes its events (ON DELETE CASCADE), so POST /api/demo/reset, which deletes
-- every trip, clears this table too.

CREATE TABLE disruption_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id      BIGINT                   NOT NULL REFERENCES trips (id) ON DELETE CASCADE,
    block_id     BIGINT                   NOT NULL REFERENCES blocks (id) ON DELETE CASCADE, -- the block that changed
    kind         VARCHAR(16)              NOT NULL, -- DELAY, CANCEL, GATE_CHANGE, MISSED
    detail       VARCHAR(500),                      -- plain English, e.g. 'Delayed by 90 minutes (mock flight status)'
    detected_at  TIMESTAMP WITH TIME ZONE NOT NULL  -- when the backend noticed it
);
