-- V1: the first three tables. A trip is a chain of blocks (one booking or event with a time: flight, cab,
-- meeting, ...) joined by links ("block B starts at least N minutes after block A ends").
--
-- How Flyway uses this folder: at startup it runs every V<number>__<name>.sql file that has not run yet, in number
-- order, and notes each one in its own table "flyway_schema_history". So:
--   * NEVER edit this file once it has run on a shared database (Supabase, a teammate's laptop): Flyway sees the
--     change and stops the app. To change the tables, add a new file, e.g. V2__create_plan_options.sql.
--   * Local database only? "docker compose down -v" wipes it, and the next start runs everything again.
--
-- The SQL must run unchanged on PostgreSQL 17 (Docker, Supabase) AND on H2 in PostgreSQL mode (the in-memory test
-- database), so it uses only plain standard SQL: VARCHAR instead of TEXT, no PostgreSQL-only features.
--
-- Columns with a fixed list of values (purpose, status, ...) hold the Java enum's name as text, e.g. 'BUSINESS'.
-- Times are TIMESTAMP WITH TIME ZONE: an exact moment. The API shows them in Indian time (+05:30).
-- Deleting a trip also deletes its blocks and links (ON DELETE CASCADE), and deleting a block deletes its links.

CREATE TABLE trips (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 1, 2, 3, ... handed out by the database
    title       VARCHAR(200)             NOT NULL,
    purpose     VARCHAR(32)              NOT NULL, -- BUSINESS, WEDDING, HOLIDAY, PILGRIMAGE, MEDICAL, EXAM
    persona     VARCHAR(32)              NOT NULL, -- FIRST_TIME, FAMILY, BUSINESS, ELDERLY
    language    VARCHAR(8)               NOT NULL, -- en, hi, mr, ta, bn
    travellers  INT                      NOT NULL,
    status      VARCHAR(16)              NOT NULL, -- PLANNED, ACTIVE, DONE
    version     INT                      NOT NULL, -- starts at 1, +1 on every plan change; the app compares it
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE blocks (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id                    BIGINT                   NOT NULL REFERENCES trips (id) ON DELETE CASCADE,
    type                       VARCHAR(32)              NOT NULL, -- FLIGHT, BAG_CLAIM, CAB, HOTEL, MEETING, EVENT, RESTAURANT, TRAIN, OTHER
    title                      VARCHAR(200)             NOT NULL,
    start_time                 TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time                   TIMESTAMP WITH TIME ZONE NOT NULL,
    location_name              VARCHAR(200),
    lat                        DOUBLE PRECISION,
    lng                        DOUBLE PRECISION,
    provider                   VARCHAR(32)              NOT NULL, -- MOCK_AIR, MOCK_STAY, MOCK_CAB, MOCK_TABLE, GOOGLE_CALENDAR, NONE
    provider_ref               VARCHAR(64),                       -- booking reference at the provider; NULL = nothing booked
    flex                       VARCHAR(16)              NOT NULL, -- FIXED, AUTO_SHIFT, ASK_USER
    anchor                     BOOLEAN                  NOT NULL, -- TRUE = the block the traveller must not miss
    status                     VARCHAR(16)              NOT NULL, -- OK, AUTO_ADJUSTED, NEEDS_USER, DONE, CANCELLED
    free_change_until_minutes  INT,                               -- minutes from the start, e.g. -30; NULL = never free
    change_fee_inr             INT                      NOT NULL, -- whole rupees
    notes                      VARCHAR(1000)
);

CREATE TABLE links (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id          BIGINT      NOT NULL REFERENCES trips (id) ON DELETE CASCADE,
    from_block_id    BIGINT      NOT NULL REFERENCES blocks (id) ON DELETE CASCADE,
    to_block_id      BIGINT      NOT NULL REFERENCES blocks (id) ON DELETE CASCADE,
    min_gap_minutes  INT         NOT NULL,
    travel_minutes   INT         NOT NULL,
    travel_mode      VARCHAR(16) NOT NULL -- WALK, CAB, METRO, NONE
);

-- The API always loads blocks and links by trip id. PostgreSQL does not index foreign keys by itself.
CREATE INDEX idx_blocks_trip_id ON blocks (trip_id);
CREATE INDEX idx_links_trip_id ON links (trip_id);
