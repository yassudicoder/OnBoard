-- V4 (Disruption Recovery, phase C2): recovery plans and their alternatives, plus the facts a plan depends on.
--
--  1. Connections remember the traveller's choices and confirmed facts: urgency (NORMAL / URGENT), the flight the
--     airline rebooked them on (and its departure, when known) and when the connection was resolved.
--  2. recovery_plans: at most one plan per connection, rebuilt on every change in the same transaction as the change
--     (watcher.DisruptionService). A connection that is fine again keeps its row with active = FALSE.
--  3. alternative_options: the checked and ranked alternatives of a plan (and the rejected ones, with the reason),
--     replaced on every rebuild. option_json holds the ready-to-send details (legs, checks, notes, reason).
--
-- Same rules as V1 (read its header): never edit this file once it has run on a shared database; plain SQL for
-- PostgreSQL 17 and H2; one change per ALTER TABLE statement. "trigger" and "rank" are SQL words, hence
-- trigger_kind and rank_order.

-- 1. Facts on connections.
ALTER TABLE connections ADD COLUMN urgency VARCHAR(8) DEFAULT 'NORMAL' NOT NULL;     -- NORMAL, URGENT
ALTER TABLE connections ADD COLUMN rebooked_flight VARCHAR(16);                      -- e.g. 'MJ 33'; NULL = none
ALTER TABLE connections ADD COLUMN rebooked_departure TIMESTAMP WITH TIME ZONE;     -- NULL = not known
ALTER TABLE connections ADD COLUMN resolved_at TIMESTAMP WITH TIME ZONE;            -- NULL = not resolved

-- 2. Plans.
CREATE TABLE recovery_plans (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id                BIGINT                   NOT NULL REFERENCES trips (id) ON DELETE CASCADE,
    connection_id          BIGINT                   NOT NULL REFERENCES connections (id) ON DELETE CASCADE,
    active                 BOOLEAN                  NOT NULL, -- FALSE = the connection needs no plan (any more)
    trigger_kind           VARCHAR(32)              NOT NULL, -- DELAY_MISSED_CONNECTION, CANCELLED_BEFORE_DEPARTURE, CONNECTION_CANCELLED_AT_HUB
    start_airport          VARCHAR(3)               NOT NULL, -- where the plan starts, e.g. 'DOH'
    destination            VARCHAR(3)               NOT NULL, -- e.g. 'LHR'
    earliest_departure     TIMESTAMP WITH TIME ZONE NOT NULL, -- alternatives leave at or after this
    urgency                VARCHAR(8)               NOT NULL, -- the ranking used
    ticket_type            VARCHAR(16)              NOT NULL, -- the ticket type used
    version                INT                      NOT NULL, -- 1, then +1 on every rebuild
    generated_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    based_on_data_at       TIMESTAMP WITH TIME ZONE NOT NULL, -- the connection's data_as_of when built
    recommended_option_id  BIGINT,                            -- alternative_options.id; NULL = no option
    steps_json             VARCHAR(10000)           NOT NULL, -- the numbered next steps
    overnight_json         VARCHAR(10000)           NOT NULL, -- the Overnight section (needed = false when not)
    where_to_go            VARCHAR(1000)            NOT NULL, -- "On arrival in Doha: follow signs to Transfers ..."
    CONSTRAINT uq_recovery_plans_connection UNIQUE (connection_id)
);

CREATE INDEX idx_recovery_plans_trip_id ON recovery_plans (trip_id);

-- 3. Alternatives.
CREATE TABLE alternative_options (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id                  BIGINT                   NOT NULL REFERENCES recovery_plans (id) ON DELETE CASCADE,
    rank_order               INT                      NOT NULL, -- 1 = best score; rejected options: 0
    recommended              BOOLEAN                  NOT NULL,
    rejected                 BOOLEAN                  NOT NULL, -- TRUE = fails a minimum connection time
    route_key                VARCHAR(300)             NOT NULL, -- same flights at the same times = same key
    departs                  TIMESTAMP WITH TIME ZONE NOT NULL,
    arrives                  TIMESTAMP WITH TIME ZONE NOT NULL,
    stops                    INT                      NOT NULL,
    connection_time_checked  BOOLEAN                  NOT NULL,
    transit_visa_status      VARCHAR(16)              NOT NULL, -- OK, REQUIRED, UNKNOWN
    seat_availability        VARCHAR(16)              NOT NULL, -- VERIFIED, UNKNOWN
    fare_difference_inr      INT,                               -- only for separate tickets
    separate_tickets         BOOLEAN                  NOT NULL,
    source                   VARCHAR(16)              NOT NULL, -- SAMPLE, PROVIDER
    option_json              VARCHAR(20000)           NOT NULL  -- legs, connection checks, notes, reason
);

CREATE INDEX idx_alternative_options_plan_id ON alternative_options (plan_id);
